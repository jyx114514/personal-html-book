async function select(page, selector, text) {
  await page.locator(selector).scrollIntoViewIfNeeded()
  await page.evaluate(({ selector, text }) => {
    document.activeElement?.blur()
    const host = document.querySelector(selector), whole = host.textContent
    const start = text ? whole.indexOf(text) : 0, end = text ? start + text.length : whole.length
    if (start < 0) throw new Error('Test quote missing')
    const walker = document.createTreeWalker(host, NodeFilter.SHOW_TEXT), nodes = []
    let offset = 0
    for (let node = walker.nextNode(); node; node = walker.nextNode()) { nodes.push({ node, start: offset, end: offset + node.length }); offset += node.length }
    const first = nodes.find(item => item.end > start), last = [...nodes].reverse().find(item => item.start < end)
    const range = document.createRange()
    range.setStart(first.node, start - first.start)
    range.setEnd(last.node, end - last.start)
    const selection = getSelection()
    selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  }, { selector, text })
  await page.getByRole('toolbar').waitFor({ state: 'visible' })
}
const stored = page => page.evaluate(() => JSON.parse(localStorage.getItem('course-annotations:v1:notes-zh')).records)
async function clickFirstWord(page, selector) {
  const point = await page.locator(selector).evaluate(host => {
    const walker = document.createTreeWalker(host, NodeFilter.SHOW_TEXT)
    let node = walker.nextNode()
    while (node && !node.textContent.trim()) node = walker.nextNode()
    const range = document.createRange(); range.setStart(node, 0); range.setEnd(node, Math.min(4, node.textContent.length))
    const rect = range.getBoundingClientRect()
    return { x: rect.left + rect.width / 2, y: rect.top + rect.height / 2 }
  })
  await page.mouse.click(point.x, point.y)
}
async function more(page) {
  const menu = page.locator('.course-notes-menu')
  if (!await menu.evaluate(node => node.open)) await menu.locator('summary').click()
}

test('new selections never preselect or inherit the last color while existing marks show their actual color', async t => {
  const { browser, url } = await prepare(t)
  const context = await browser.newContext({ offline: true })
  t.after(() => context.close())
  const page = await context.newPage()
  await page.goto(url('zh'))
  await page.evaluate(() => localStorage.setItem('course-annotations:v1:notes-zh:pens', JSON.stringify({ pen: 'highlight', highlight: 'blue', underline: 'orange' })))
  await page.reload()
  const toolbar = page.getByRole('toolbar'), selectedColors = toolbar.locator('[data-color][aria-pressed="true"]')
  await select(page, '#first')
  assert.equal(await selectedColors.count(), 0, 'Stored legacy color preferences must not preselect a new quote')
  assert.equal(await page.evaluate(() => localStorage.getItem('course-annotations:v1:notes-zh')), null, 'Selecting text alone must not create a mark')
  await toolbar.getByRole('button', { name: '蓝色', exact: true }).click()
  const first = (await stored(page))[0]
  assert.equal(first.color, 'blue', 'Clicking a color must apply it immediately')
  await select(page, '#second')
  assert.equal(await selectedColors.count(), 0)
  assert.equal((await stored(page)).length, 1)
  await toolbar.getByRole('button', { name: '高亮', exact: true }).click()
  assert.equal((await stored(page)).find(row => row.id !== first.id).color, 'yellow', 'New marks use default yellow rather than the last blue')
  await select(page, '#first')
  assert.equal(await selectedColors.getAttribute('data-color'), 'blue')
  await toolbar.getByRole('button', { name: '下划线', exact: true }).click()
  assert.equal((await stored(page)).find(row => row.id === first.id).color, 'blue', 'Switching an existing mark style must keep its actual color')
  await select(page, '#third')
  assert.equal(await selectedColors.count(), 0)
  await toolbar.getByRole('button', { name: '笔记', exact: true }).click()
  assert.equal(await page.locator('.course-notes-editor').getAttribute('data-color'), 'yellow')
  await page.keyboard.press('Control+Enter')
  await page.reload()
  await select(page, '#same-a')
  assert.equal(await selectedColors.count(), 0, 'Reopening must not restore a preselected color')
  await page.keyboard.press('Control+Alt+h')
  assert.equal((await stored(page)).find(row => row.anchor.exact === 'Repeated sentence.').color, 'yellow')
})

